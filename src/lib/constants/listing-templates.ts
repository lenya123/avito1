/**
 * Шаблоны описаний для объявлений Авито — по категории товара.
 *
 * Скелет вставляется по кнопке «Шаблон» (форма товара + модалка «Создать
 * объявление»), владелец заполняет поля. Структура полей взята из дроп-канала
 * (Материал / Качество / Размеры / Производство), но адаптирована под чистый
 * Avito-тон: без цены, без призывов писать менеджеру, без эмодзи-спама.
 *
 * Это «база» товара (`products.description`). На каждое объявление из неё
 * генерируется УНИКАЛЬНЫЙ маркетинговый текст (см. `generateListingContent`).
 *
 * Канон-список категорий — `product-categories.ts`.
 */
import type { ProductCategory } from "./product-categories";

export const CATEGORY_DESCRIPTION_TEMPLATES: Record<ProductCategory, string> = {
  "Верхняя одежда": `Модель:
Материал:
Утеплитель/подкладка:
Фасон и посадка:
Доступные размеры:
Уход:
Производство: `,

  "Нижняя одежда": `Модель:
Материал:
Посадка (низкая/средняя/высокая):
Крой (зауженный/прямой/свободный):
Доступные размеры:
Уход:
Производство: `,

  Костюмы: `Состав комплекта:
Материал:
Фасон и посадка:
Подкладка:
Доступные размеры:
Уход:
Производство: `,

  Аксессуары: `Тип:
Материал:
Размер/габариты:
Фурнитура:
Особенности:
Производство: `,

  Обувь: `Модель:
Материал верха:
Подошва:
Сезон:
Доступные размеры:
Уход:
Производство: `,
};

/** Шаблон по категории; null если категория не выбрана/неизвестна. */
export function templateFor(category: string | null | undefined): string | null {
  if (!category) return null;
  return CATEGORY_DESCRIPTION_TEMPLATES[category as ProductCategory] ?? null;
}
