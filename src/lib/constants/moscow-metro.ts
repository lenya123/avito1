/** Москва: коричневое кольцо + БКЛ — единый пул для разброса локаций. */
export const MOSCOW_METRO = [...MOSCOW_RING_METRO, ...MOSCOW_BKL_METRO] as const;

export type MoscowRingMetro = (typeof MOSCOW_RING_METRO)[number];
export type MoscowMetro = (typeof MOSCOW_METRO)[number];

/** Случайная станция коричневого кольца. */
export function randomRingMetro(): MoscowRingMetro {
  return MOSCOW_RING_METRO[Math.floor(Math.random() * MOSCOW_RING_METRO.length)];
}

/** Случайная станция Москвы (кольцо + БКЛ) — для локации объявления. */
export function randomMoscowMetro(): MoscowMetro {
  return MOSCOW_METRO[Math.floor(Math.random() * MOSCOW_METRO.length)];
}
