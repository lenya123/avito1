export function resolveAvitoBrandId(brand?: string | null): string {
  if (!brand) return AVITO_BRAND_NO;
  const norm = brand.trim().toLowerCase();
  if (!norm) return AVITO_BRAND_NO;
  if (AVITO_BRAND_OPTIONS[norm]) return AVITO_BRAND_OPTIONS[norm];
  const first = norm.split(/[s,/]+/)[0];
  if (first && AVITO_BRAND_OPTIONS[first]) return AVITO_BRAND_OPTIONS[first];
  return AVITO_BRAND_NO;
}
