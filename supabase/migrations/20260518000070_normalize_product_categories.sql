-- Категории товаров стали фиксированным списком из 5 значений
-- (src/lib/constants/product-categories.ts). Раньше — свободный текст.
-- Чистим хвосты: всё, что НЕ входит в новый список, → NULL
-- («Без категории»; владелец заново выберет из выпадающего списка).
-- Точные совпадения («Верхняя одежда», «Аксессуары», «Обувь»)
-- сохраняются. Затрагиваем все строки (вкл. удалённые) — чтобы хвостов
-- не осталось нигде.

UPDATE public.products
   SET category = NULL
 WHERE category IS NOT NULL
   AND category <> ALL (ARRAY[
     'Верхняя одежда',
     'Нижняя одежда',
     'Костюмы',
     'Аксессуары',
     'Обувь'
   ]);
