-- ============================================================================
-- ТЗ Авито-заказы (§9.5): логирование AI ↔ покупатель сообщений
-- для аудита и будущей доработки качества мини-AI.
--
-- Переиспользуем существующую таблицу avito_messages (direction in/out),
-- добавляем два поля:
--
--   is_ai_generated — TRUE если исходящее сообщение сгенерировал мини-AI
--                     (отделяет от ручных сообщений владельца/директора).
--   parsed_size     — если входящее сообщение от покупателя распарсилось
--                     как размер (M, L, XL, ...) — сохраняем распознанное
--                     значение. NULL если не размер / не распарсено.
-- ============================================================================

ALTER TABLE public.avito_messages
  ADD COLUMN IF NOT EXISTS is_ai_generated BOOLEAN     NOT NULL DEFAULT FALSE,
  ADD COLUMN IF NOT EXISTS parsed_size     VARCHAR(10);
