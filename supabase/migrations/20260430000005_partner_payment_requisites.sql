-- Возврат к статичным реквизитам партнёра (Phase G.2 v2).
--
-- Колонка `partners.payment_requisites` была удалена миграцией
-- 20260429000007 (откат G.2 утром того же дня). К концу дня владелец
-- передумал — статичные реквизиты возвращаются с поддержкой двух типов:
-- текст (карта/СБП/ИП) и фото с QR-кодом.
--
-- Структура JSON:
--   {"type": "text", "value": "Сбер 4276 ..."}
--   {"type": "photo", "file_id": "AgACA..."}
--
-- При оформлении партнёрского заказа клиенту сразу показываются эти
-- реквизиты (без ожидания партнёра). Партнёр получает уведомление
-- только после получения чека от клиента (см. фазу 1, экран 4 (г)).
--
-- Если у партнёра payment_requisites IS NULL — его товары не должны
-- появляться в клиентском каталоге (фильтр будет добавлен в коде).

ALTER TABLE partners ADD COLUMN payment_requisites JSONB;

COMMENT ON COLUMN partners.payment_requisites IS
  'Статичные реквизиты для оплаты от клиентов. type=text|photo. См. §10.2 канона.';
