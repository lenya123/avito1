-- Ступени ротации платёжных методов (3 уровня).
--
-- tier=1 — самые ходовые карты, идут первыми. Внутри ступени — равномерная
--          ротация по проценту заполнения месячного лимита.
-- tier=2 — запасные. Подключаются когда tier=1 исчерпали лимиты.
-- tier=3 — последний резерв (исторически здесь ИП-QR, но владелец решает).
--
-- Внутри одной ступени — pro-rata: берём ту карту, у которой меньший процент
-- заполнения (`amount_used / monthly_limit`). Карты без лимита считаются
-- условно «свободными» (ratio=0). Между ступенями — строгий fallback:
-- следующая ступень не используется пока на текущей есть хоть одна карта
-- с не-исчерпанным лимитом.
--
-- Backfill: при импорте все существующие методы → tier=1 (владелец потом
-- сам распределит через UI).

ALTER TABLE public.payment_methods
  ADD COLUMN IF NOT EXISTS tier INT NOT NULL DEFAULT 1
    CHECK (tier IN (1, 2, 3));

COMMENT ON COLUMN public.payment_methods.tier IS
  'Ступень ротации (1=основные, 2=запасные, 3=резерв). Внутри ступени pro-rata по проценту заполнения месячного лимита.';
